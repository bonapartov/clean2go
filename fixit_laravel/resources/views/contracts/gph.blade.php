3. ПОРЯДОК ОКАЗАНИЯ УСЛУГ
3.1. Исполнитель принимает заказы через мобильное приложение Fixit Russia (далее — «Приложение»). Принятие заказа фиксируется Приложением и является акцептом задания в рамках настоящего Договора.
3.2. Исполнитель обязан:
• оказывать Услуги в сроки, указанные в заказе;
• соблюдать стандарты качества Fixit Russia, ознакомившись с ними при регистрации;
• иметь при себе документ, удостоверяющий личность, при выезде на заказ;
• бережно относиться к имуществу Клиента и Заказчика;
• незамедлительно сообщать Заказчику о невозможности исполнить заказ.
3.3. Факт оказания Услуг подтверждается электронной отметкой в Приложении («Выполнено») с фотоподтверждением результата и оценкой Клиента. Данная отметка является основанием для начисления вознаграждения.
3.4. По итогам каждого календарного месяца Заказчик формирует и направляет Исполнителю Акт приёмки-сдачи оказанных услуг (далее — «Акт»). Акт считается принятым Исполнителем, если в течение 3 (трёх) рабочих дней с момента направления Исполнитель не направил мотивированных возражений.

4. ВОЗНАГРАЖДЕНИЕ И ПОРЯДОК РАСЧЁТОВ
4.1. Вознаграждение Исполнителя за каждый заказ определяется в соответствии с ценовой политикой платформы Fixit Russia, действующей на дату выполнения заказа, за вычетом комиссии Заказчика в размере 15% (пятнадцати процентов) от стоимости заказа.
4.2. Сумма к выплате Исполнителю рассчитывается по формуле:
Выплата = Стоимость заказа × (1 − Комиссия%) × (1 − 0,13)
где 0,13 — ставка НДФЛ, удерживаемого Заказчиком как налоговым агентом.
4.3. Выплата вознаграждения производится в течение 5 (пяти) рабочих дней после подписания ежемесячного Акта путём перечисления на банковский счёт Исполнителя, указанный в разделе 10 настоящего Договора, либо через электронный кошелёк платформы.
4.4. Выплата вознаграждения приостанавливается в следующих случаях:
• поступления обоснованной претензии от Клиента в отношении качества оказанных Услуг — до урегулирования претензии;
• нарушения Исполнителем условий настоящего Договора или Правил платформы;
• выявления судебного решения о взыскании с Исполнителя задолженности в пользу третьих лиц.
4.5. Заказчик вправе удержать из вознаграждения Исполнителя суммы ущерба, причинённого Клиентам и/или Заказчику по вине Исполнителя, при условии документального подтверждения такого ущерба.

