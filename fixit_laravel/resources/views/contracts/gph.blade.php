8.3. За нарушение сроков выплаты вознаграждения Заказчик уплачивает Исполнителю пени в размере 0,1% от суммы задолженности за каждый день просрочки, но не более 10% от суммы задолженности.
8.4. Стороны освобождаются от ответственности за неисполнение или ненадлежащее исполнение обязательств вследствие форс-мажорных обстоятельств: стихийных бедствий, военных действий, действий государственных органов и иных обстоятельств непреодолимой силы.
8.5. В случае нарушения Исполнителем оговорки о неконкуренции (п. 7.1) Заказчик вправе в одностороннем порядке расторгнуть настоящий Договор и удержать все невыплаченные суммы вознаграждения в качестве возмещения убытков.

