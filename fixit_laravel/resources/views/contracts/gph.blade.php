• нарушения Исполнителем требований по конфиденциальности персональных данных;
• предоставления Исполнителем заведомо ложных сведений при регистрации на платформе.
10.4. При расторжении Договора Заказчик обязан произвести окончательный расчёт с Исполнителем по всем выполненным и принятым заказам в течение 10 (десяти) рабочих дней.

