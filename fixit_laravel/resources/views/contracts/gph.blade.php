• проводить проверку соответствия Исполнителя требованиям платформы, включая запросы о наличии судимостей.

6. ПРАВА И ОБЯЗАННОСТИ ИСПОЛНИТЕЛЯ
6.1. Исполнитель обязан:
• лично оказывать Услуги по принятым заказам;
• соответствовать требованиям к квалификации, предъявляемым Заказчиком;
