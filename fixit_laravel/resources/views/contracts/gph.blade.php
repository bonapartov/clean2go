2. ПРАВОВОЙ СТАТУС ИСПОЛНИТЕЛЯ
2.1. Исполнитель является физическим лицом, не имеющим статуса индивидуального предпринимателя и статуса плательщика налога на профессиональный доход (НПД) на дату заключения настоящего Договора.
2.2. В соответствии с требованиями Налогового кодекса Российской Федерации Заказчик является налоговым агентом Исполнителя. Заказчик обязан:
• исчислять и удерживать налог на доходы физических лиц (НДФЛ) по ставке 13% от суммы вознаграждения Исполнителя;
• перечислять удержанный НДФЛ в бюджет Российской Федерации в установленные законом сроки;
• представлять в налоговые органы расчёт по форме 6-НДФЛ в установленные сроки;
• предоставлять Исполнителю справку по форме 2-НДФЛ по его письменному требованию.
2.3. Сумма, выплачиваемая Исполнителю, является суммой за вычетом НДФЛ (чистое вознаграждение). Страховые взносы на обязательное пенсионное, медицинское и социальное страхование начисляются Заказчиком на сумму вознаграждения сверх указанной суммы и уплачиваются за счёт Заказчика.
2.4. Исполнитель уведомлён о необходимости самостоятельно оценивать целесообразность оформления статуса индивидуального предпринимателя или самозанятого (НПД) для оптимизации налоговой нагрузки. В случае получения Исполнителем статуса НПД Стороны вправе заключить дополнительное соглашение об изменении налогового режима в рамках настоящего Договора.
