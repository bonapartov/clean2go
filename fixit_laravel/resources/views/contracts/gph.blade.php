• немедленно сообщать Заказчику о любых обстоятельствах, препятствующих исполнению заказа;
• не осуществлять с Клиентами Заказчика прямые расчёты за оказанные через платформу Услуги, минуя платёжную систему платформы.
6.2. Исполнитель вправе:
