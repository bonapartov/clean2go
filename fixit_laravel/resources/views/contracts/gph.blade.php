7.2. Нарушение настоящей оговорки влечёт обязательство Исполнителя уплатить Заказчику штраф в размере 50 000 (пятидесяти тысяч) рублей за каждый случай нарушения, а также возместить все убытки, превышающие размер штрафа.
7.3. Настоящая оговорка не распространяется на случаи, когда Клиент самостоятельно нашёл Исполнителя вне платформы и письменно подтвердил данный факт.

8. ОТВЕТСТВЕННОСТЬ СТОРОН
8.1. За ненадлежащее оказание Услуг, повлёкшее ущерб имуществу Клиента, Исполнитель несёт ответственность в размере реального ущерба, подтверждённого документально.
