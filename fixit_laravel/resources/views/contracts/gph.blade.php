1. ПРЕДМЕТ ДОГОВОРА
1.1. Исполнитель обязуется по заданию Заказчика оказать услуги в сфере клининга, бытового ремонта и сопутствующих работ (далее — «Услуги») через технологическую платформу Fixit Russia, а Заказчик обязуется принять и оплатить оказанные Услуги в порядке, предусмотренном настоящим Договором.
