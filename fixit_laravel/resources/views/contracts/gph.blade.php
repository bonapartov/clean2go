10. СРОК ДЕЙСТВИЯ И РАСТОРЖЕНИЕ ДОГОВОРА
10.1. Настоящий Договор вступает в силу с момента его подписания Сторонами и действует в течение 1 (одного) года. Если ни одна из Сторон не уведомит другую о намерении расторгнуть Договор за 30 (тридцать) календарных дней до окончания срока, Договор считается пролонгированным на тот же срок.
10.2. Каждая из Сторон вправе расторгнуть настоящий Договор в одностороннем порядке, направив письменное уведомление другой Стороне за 14 (четырнадцать) календарных дней до предполагаемой даты расторжения.
10.3. Заказчик вправе расторгнуть Договор без предварительного уведомления в случае:
• нарушения Исполнителем оговорки о неконкуренции;
