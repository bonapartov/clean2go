9.1. Настоящий Договор подписывается уполномоченными представителями Сторон. При подписании через систему Fixit Russia применяется усиленная квалифицированная или простая электронная подпись.
9.2. Изменения в Договор вносятся путём подписания дополнительных соглашений.
9.3. Все споры рассматриваются в Арбитражном суде г. Москвы.
9.4. Договор составлен в двух экземплярах, имеющих равную юридическую силу, по одному для каждой из Сторон.
