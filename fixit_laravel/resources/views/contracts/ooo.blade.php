1. ПРЕДМЕТ ДОГОВОРА
1.1. Субподрядчик обязуется по заданиям Генерального подрядчика оказывать услуги в сфере клининга и/или бытового ремонта (далее — «Услуги») конечным заказчикам (клиентам Платформы), а Генеральный подрядчик обязуется принять и оплатить надлежащим образом оказанные Услуги.
1.2. Конкретный вид, объём, место, время и стоимость Услуг определяются в Заданиях, направляемых через систему Fixit Russia.
1.3. Субподрядчик оказывает Услуги силами своих квалифицированных работников. Привлечение третьих лиц возможно только с письменного согласия Генерального подрядчика.
1.4. Субподрядчик обязан обеспечить наличие у исполнителей всей необходимой квалификации, инструментов, спецодежды и допусков, требуемых для выполнения конкретных Услуг.
2. ПОРЯДОК ВЫПОЛНЕНИЯ УСЛУГ
2.1. Задание считается принятым Субподрядчиком с момента его подтверждения в системе Fixit Russia.
2.2. Субподрядчик обеспечивает прибытие исполнителей к месту оказания Услуги строго в согласованное время.
2.3. Субподрядчик соблюдает стандарты качества Генерального подрядчика, включая: внешний вид исполнителей; наличие именных бейджей; фотофиксацию «до» и «после»; заполнение чек-листов по завершении работы.
2.4. По завершении оказания Услуги Субподрядчик отмечает выполнение в системе. Клиент подтверждает приёмку. Стороны подписывают Акт об оказании услуг.
2.5. При наличии претензий клиента Субподрядчик обязан устранить недостатки в течение 24 (двадцати четырёх) часов или предоставить обоснованный план устранения.
3. ДОКУМЕНТООБОРОТ
3.1. По итогам каждого календарного месяца Субподрядчик выставляет счёт и направляет Акт об оказанных услугах на основании данных системы Fixit Russia.
3.2. Генеральный подрядчик обязан рассмотреть Акт и подписать его или направить мотивированный отказ в течение 5 (пяти) рабочих дней.
3.3. При отсутствии ответа в указанный срок Акт считается принятым Генеральным подрядчиком.
3.4. Субподрядчик выставляет счёт-фактуру (при применении ОСНО) или счёт (при применении УСН) в соответствии со своим налоговым режимом.
4. СТОИМОСТЬ И ПОРЯДОК РАСЧЁТОВ
4.1. Вознаграждение Субподрядчика составляет стоимость оказанных Услуг за вычетом комиссии Генерального подрядчика в размере 15% (пятнадцати процентов) от стоимости каждого Задания.
4.2. Оплата производится в течение 5 (пяти) рабочих дней с момента подписания ежемесячного Акта и выставления счёта путём перечисления на расчётный счёт Субподрядчика.
4.3. НДС: если Субподрядчик является плательщиком НДС — стоимость Услуг указывается с учётом НДС, который возмещается дополнительно к цене Договора. Если Субподрядчик применяет УСН — НДС не предъявляется.
4.4. Субподрядчик самостоятельно исчисляет и уплачивает все налоги и обязательные платежи, связанные с его деятельностью.
5. КОНФИДЕНЦИАЛЬНОСТЬ И НЕКОНКУРЕНЦИЯ
5.1. Субподрядчик обязуется не разглашать персональные данные клиентов, коммерческую тайну и техническую документацию Генерального подрядчика.
5.2. Субподрядчик обязуется в течение 24 (двадцати четырёх) месяцев с момента последнего Задания не предоставлять аналогичные услуги клиентам Генерального подрядчика напрямую, минуя систему Fixit Russia.
5.3. Нарушение пункта 5.2 влечёт уплату штрафа в размере 100 000 рублей за каждый доказанный случай плюс возмещение упущенной выгоды.
6. ОТВЕТСТВЕННОСТЬ
6.1. Субподрядчик несёт полную ответственность за качество оказанных Услуг и действия своих работников.
6.2. Субподрядчик несёт ответственность за ущерб, причинённый имуществу или здоровью клиента, в полном объёме причинённого вреда.
6.3. Генеральный подрядчик страхует гражданскую ответственность в рамках каждого заказа. При недостаточности страхового покрытия ответственность несёт Субподрядчик.
6.4. За систематическое нарушение стандартов качества (более 2 случаев в месяц с рейтингом ниже 3,5) Генеральный подрядчик вправе взыскать штраф в размере 5 000 рублей за каждый подтверждённый случай.
6.5. В случае задержки выплаты по вине Генерального подрядчика более чем на 5 рабочих дней начисляется пени в размере 0,1% за каждый день просрочки.
7. ПРОВЕРКИ И КОНТРОЛЬ КАЧЕСТВА
7.1. Генеральный подрядчик вправе проводить контрольные проверки качества оказываемых Услуг, в том числе методом «тайного покупателя».
7.2. Субподрядчик обязан предоставлять по запросу Генерального подрядчика сведения о своих работниках (ФИО, гражданство, разрешение на работу при необходимости).
7.3. Генеральный подрядчик вправе отстранить конкретного работника Субподрядчика от выполнения заданий при наличии обоснованных претензий клиентов.
8. СРОК ДЕЙСТВИЯ И РАСТОРЖЕНИЕ
8.1. Договор заключается на 1 (один) год с автоматической пролонгацией на тот же срок при отсутствии возражений Сторон.
8.2. Каждая из Сторон вправе расторгнуть Договор, уведомив другую Сторону в письменном виде за 30 (тридцать) календарных дней.
8.3. Генеральный подрядчик вправе расторгнуть Договор немедленно при: систематическом нарушении стандартов качества; причинении значительного ущерба клиенту; нарушении раздела 5; ликвидации или банкротстве Субподрядчика.
8.4. При расторжении Договора Стороны проводят окончательные взаиморасчёты в течение 15 (пятнадцати) рабочих дней.
